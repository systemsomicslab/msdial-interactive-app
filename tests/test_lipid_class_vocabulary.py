class GeneratorTests(unittest.TestCase):
    def setUp(self) -> None:
        self.generator = load_generator()

    def test_the_enum_is_read_without_its_commented_members(self) -> None:
        self.assertEqual(["Cer", "PC", "Cer_NS", "LipidA", "Undefined"],
                         self.generator.parse_lbm_class_enum(SYNTHETIC_ENUM))

    def test_only_the_live_switch_is_read_and_stacked_cases_share_their_return(self) -> None:
        table = self.generator.parse_enum_to_vs2(SYNTHETIC_CONVERTER)
        self.assertEqual({"PC": "PC", "Cer_NS": "Cer-NS", "Cer": "Cer-NS"}, table)

    def test_the_name_switch_accepts_both_spellings(self) -> None:
        table = self.generator.parse_name_to_enum(SYNTHETIC_CONVERTER)
        self.assertEqual({"PC": "PC", "Cer-NS": "Cer_NS", "Cer_NS": "Cer_NS"}, table)

    def test_a_switch_that_is_not_found_is_an_error_rather_than_an_empty_table(self) -> None:
        with self.assertRaises(ValueError):
            self.generator.parse_enum_to_vs2("public static class LipidomicsConverter { }")


@unittest.skipUnless(
    os.environ.get("MSDIAL_WORKBENCH_SOURCE"),
    "set MSDIAL_WORKBENCH_SOURCE to an MsdialWorkbench checkout to compare the resource with it",
)
class ResourceAgainstSourceTests(unittest.TestCase):
    def test_the_resource_is_what_the_source_generates(self) -> None:
        generator = load_generator()
        lines = generator.vocabulary_lines(Path(os.environ["MSDIAL_WORKBENCH_SOURCE"]), "checkout")
        current = VOCABULARY_PATH.read_text(encoding="ascii").splitlines()
        self.assertEqual(
            [line for line in current if not line.startswith("#")],
            [line for line in lines if not line.startswith("#")],
        )


