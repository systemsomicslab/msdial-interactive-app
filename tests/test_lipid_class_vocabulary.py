"""The lipid class vocabulary, and the generator that reads it out of MS-DIAL's source."""

from __future__ import annotations

import importlib.util
import os
import unittest
from pathlib import Path

from msdial_app.lab_lipidomics import VOCABULARY_PATH, load_lipid_class_vocabulary

ROOT = Path(__file__).resolve().parent.parent
GENERATOR = ROOT / "scripts" / "generate-lipid-class-vocabulary.py"
# The 28 classes whose VS2 definition is not the enum name: always the first underscore as a
# hyphen. Sheet 2 must use the right-hand spelling, sheet 3 and the exports the left-hand one.
DIFFERING = {
    "Cer_ADS": "Cer-ADS", "Cer_AS": "Cer-AS", "Cer_BDS": "Cer-BDS", "Cer_BS": "Cer-BS",
    "Cer_EODS": "Cer-EODS", "Cer_EOS": "Cer-EOS", "Cer_NDS": "Cer-NDS", "Cer_NS": "Cer-NS",
    "Cer_NP": "Cer-NP", "Cer_AP": "Cer-AP", "Cer_OS": "Cer-OS", "Cer_EBDS": "Cer-EBDS",
    "HexCer_NS": "HexCer-NS", "HexCer_NDS": "HexCer-NDS", "HexCer_AP": "HexCer-AP",
    "HexCer_EOS": "HexCer-EOS", "PE_Cer": "PE-Cer", "PI_Cer": "PI-Cer", "Cer_HS": "Cer-HS",
    "HexCer_HS": "HexCer-HS", "Cer_NDOS": "Cer-NDOS", "Cer_HDS": "Cer-HDS", "HexCer_HDS": "HexCer-HDS",
    "Cer_ABP": "Cer-ABP", "Cer_AH": "Cer-AH", "Cer_NH": "Cer-NH", "Cer_AH_d9": "Cer-AH_d9",
    "Cer_NH_d9": "Cer-NH_d9",
}


def load_generator():
    spec = importlib.util.spec_from_file_location("generate_lipid_class_vocabulary", GENERATOR)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class VocabularyResourceTests(unittest.TestCase):
    def setUp(self) -> None:
        self.vocabulary = load_lipid_class_vocabulary()

    def test_exactly_the_28_known_classes_are_spelled_differently(self) -> None:
        differing = {
            member: vs2 for member, vs2 in self.vocabulary.enum_to_vs2.items()
            if vs2 != "Undefined" and vs2 != member
        }
        self.assertEqual(DIFFERING, differing)

    def test_every_other_defined_class_keeps_its_enum_name(self) -> None:
        for member, vs2 in self.vocabulary.enum_to_vs2.items():
            if vs2 != "Undefined" and member not in DIFFERING:
                self.assertEqual(member, vs2)

    def test_members_without_a_definition_include_the_ones_sheet_three_lists(self) -> None:
        undefined = {member for member, vs2 in self.vocabulary.enum_to_vs2.items() if vs2 == "Undefined"}
        self.assertEqual(24, len(undefined))
        self.assertTrue({"LipidA", "OxPA", "Undefined", "Others", "Unknown", "SPLASH"} <= undefined)

    def test_both_spellings_of_a_ceramide_read_as_the_same_member(self) -> None:
        self.assertEqual("Cer_AH_d9", self.vocabulary.lbm_class("Cer-AH_d9"))
        self.assertEqual("Cer_AH_d9", self.vocabulary.lbm_class("Cer_AH_d9"))
        self.assertEqual("EtherPE", self.vocabulary.lbm_class("EtherPE_P"))
        self.assertEqual("Undefined", self.vocabulary.lbm_class("Cer"))

    def test_the_vs2_list_is_get_lipid_classes(self) -> None:
        names = self.vocabulary.vs2_names
        self.assertEqual(len(names), len(set(names)))
        self.assertNotIn("Undefined", names)
        self.assertIn("Cer-NS", names)
        self.assertNotIn("Cer_NS", names)
        self.assertLess(names.index("CerP"), names.index("SM"))

    def test_the_resource_names_its_source(self) -> None:
        self.assertIn("MsdialWorkbench", self.vocabulary.source)
        self.assertTrue(VOCABULARY_PATH.read_text(encoding="ascii").startswith("# Generated by"))


