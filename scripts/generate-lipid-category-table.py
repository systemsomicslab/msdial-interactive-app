"""Generate resources/lipid_category_table.tsv from the MS-DIAL source that defines it.

The laboratory's merge program (metaboservice) files each lipid class under a lipid category
for its dotplot folders (category_<category>, Summary_Dotplots/<category>.csv) with
LipidomicsConverter.ConvertMsdialClassDefinitionToSuperClassVS2: one switch from an Ontology
to FattyAcyls, Glycerolipids, Glycerophospholipids, Sphingolipids, SterolLipids or
PrenolLipids, and "Unassigned lipid" for anything else. Interactive writes the same folders,
so the table is generated from that switch rather than typed in, the way
scripts/generate-lipid-class-vocabulary.py generates the class vocabulary.

Only active code is read: LipidomicsConverter.cs keeps a retired copy of the switch commented
out beside the live one. The source is read at the commit named, from the repository's object
store, so the commit recorded is the one read whatever the working tree holds.

    python scripts/generate-lipid-category-table.py <MsdialWorkbench checkout> [--commit <sha>]
    python scripts/generate-lipid-category-table.py <checkout> --check   # compare, write nothing

The checkout is only read. Without --commit, HEAD is read.
"""

from __future__ import annotations

import argparse
import importlib.util
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "resources" / "lipid_category_table.tsv"
CONVERTER_SOURCE = "src/Common/CommonStandard/Lipidomics/LipidomicsConverter.cs"
SWITCH = "public static string ConvertMsdialClassDefinitionToSuperClassVS2(string"


def _vocabulary_generator():
    # The comment stripper and the block reader are the vocabulary generator's: one C# reading.
    path = Path(__file__).resolve().parent / "generate-lipid-class-vocabulary.py"
    spec = importlib.util.spec_from_file_location("generate_lipid_class_vocabulary", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def parse_superclass_switch(source: str) -> tuple[list[tuple[str, str]], str]:
    """The switch's (class, category) cases in source order, and what its default returns."""
    generator = _vocabulary_generator()
    body = generator._block_after(generator.strip_comments(source), SWITCH)
    cases: list[tuple[str, str]] = []
    pending: list[str] = []
    default = None
    token = re.compile(r'case\s+"([^"]*)"\s*:|return\s+"([^"]*)"\s*;|default\s*:')
    in_default = False
    for match in token.finditer(body):
        text = match.group(0)
        if text.startswith("case"):
            if in_default:
                raise ValueError("a case label follows the default.")
            pending.append(match.group(1))
        elif text.startswith("default"):
            if pending:
                raise ValueError(f"case labels share the default: {pending}")
            in_default = True
        elif in_default:
            default = match.group(2)
            in_default = False
        else:
            if not pending:
                raise ValueError(f"a return without a case label: {text}")
            cases.extend((label, match.group(2)) for label in pending)
            pending = []
    if pending:
        raise ValueError(f"case labels without a return: {pending}")
    if default is None:
        raise ValueError("the switch has no default return.")
    seen: set[str] = set()
    for label, _ in cases:
        if label in seen:
            raise ValueError(f"'{label}' is a case twice.")
        seen.add(label)
    return cases, default


def table_lines(source: str, commit: str) -> list[str]:
    cases, default = parse_superclass_switch(source)
    lines = [
        f"# Generated by scripts/generate-lipid-category-table.py from MsdialWorkbench {commit}",
        f"# ({CONVERTER_SOURCE}, ConvertMsdialClassDefinitionToSuperClassVS2). Do not edit by hand.",
        "# case: an Ontology the switch names, and the lipid category it returns, in source order.",
        "# default: the category of every other Ontology.",
        "kind\tclass\tcategory",
    ]
    lines.extend(f"case\t{label}\t{category}" for label, category in cases)
    lines.append(f"default\t\t{default}")
    return lines


def read_source(checkout: Path, commit: str) -> str:
    result = subprocess.run(
        ["git", "-C", str(checkout), "show", f"{commit}:{CONVERTER_SOURCE}"],
        capture_output=True, check=False,
    )
    if result.returncode != 0:
        raise ValueError(result.stderr.decode("utf-8", "replace").strip() or f"git show {commit} failed")
    return result.stdout.decode("utf-8-sig")


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("checkout", type=Path, help="an MsdialWorkbench checkout, read only")
    parser.add_argument("--commit", default="HEAD", help="the commit to read (default HEAD)")
    parser.add_argument("--check", action="store_true", help="compare with the resource; write nothing")
    arguments = parser.parse_args()
    resolved = subprocess.run(
        ["git", "-C", str(arguments.checkout), "rev-parse", "--verify", f"{arguments.commit}^{{commit}}"],
        capture_output=True, text=True, check=False,
    )
    if resolved.returncode != 0:
        print(f"error: {arguments.commit} is not a commit of {arguments.checkout}", file=sys.stderr)
        return 2
    commit = resolved.stdout.strip()
    try:
        lines = table_lines(read_source(arguments.checkout, commit), commit)
    except (OSError, ValueError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    if arguments.check:
        current = OUTPUT.read_text(encoding="ascii") if OUTPUT.exists() else ""
        same = [line for line in current.splitlines() if not line.startswith("#")] == [
            line for line in lines if not line.startswith("#")
        ]
        print("unchanged" if same else "differs")
        return 0 if same else 1
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    cases = sum(1 for line in lines if line.startswith("case\t"))
    print(f"wrote {OUTPUT} ({cases} classes, commit {commit})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
