"""Generate resources/lipid_category_table.tsv from the converter metaboservice was built with.

The laboratory's merge program (metaboservice) files each lipid class under a lipid category
for its dotplot folders (category_<category>, Summary_Dotplots/<category>.csv) with
LipidomicsConverter.ConvertMsdialClassDefinitionToSuperClassVS2: one switch from an Ontology
to FattyAcyls, Glycerolipids, Glycerophospholipids, Sphingolipids, SterolLipids or
PrenolLipids, and "Unassigned lipid" for anything else. Interactive writes the same folders,
so the table is generated from that switch rather than typed in, the way
scripts/generate-lipid-class-vocabulary.py generates the class vocabulary.

The switch read is metaboservice's own: metaboservice.csproj references the CommonStandard copy
bundled beside it (metaboservice_csharp_source/CommonStandard, June 2023, 228 classes), not
MsdialWorkbench, and the 2024 binary's Common.dll agrees with that copy. Current MS-DIAL's switch
differs (248 classes): it files WE, the N-acyl amino acids (NATau, NAPhe, ...), DGTA, ASHexCer,
PT, Cer_AH/NH/ABP and others under a category where metaboservice wrote "Unassigned lipid", and
lacks GlcCer_*, GalCer_* and BA_*. The folders are what metaboservice wrote, so its copy is the
source. That copy is not under version control, so it is identified by its path below the
metaboservice source folder and its sha256.

Only active code is read: LipidomicsConverter.cs keeps a retired copy of the switch commented
out beside the live one.

    python scripts/generate-lipid-category-table.py <metaboservice_csharp_source folder, or LipidomicsConverter.cs>
    python scripts/generate-lipid-category-table.py <same> --check   # compare, write nothing

The source is only read.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import re
import sys
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "resources" / "lipid_category_table.tsv"
SOURCE_FOLDER = "metaboservice_csharp_source"
CONVERTER_SOURCE = PurePosixPath("CommonStandard/Lipidomics/LipidomicsConverter.cs")
SWITCH = "public static string ConvertMsdialClassDefinitionToSuperClassVS2(string"
SOURCE_LINE = "# source: "


def _vocabulary_generator():
    # The comment stripper and the block reader are the vocabulary generator's: one C# reading.
    path = Path(__file__).resolve().parent / "generate-lipid-class-vocabulary.py"
    spec = importlib.util.spec_from_file_location("generate_lipid_class_vocabulary", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def parse_superclass_switch(source: str) -> tuple[list[tuple[str, str]], str]:
    """The switch's (class, category) cases in source order, and what its default returns."""
    generator = _vocabulary_generator()
    body = generator._block_after(generator.strip_comments(source), SWITCH)
    cases: list[tuple[str, str]] = []
    pending: list[str] = []
    default = None
    token = re.compile(r'case\s+"([^"]*)"\s*:|return\s+"([^"]*)"\s*;|default\s*:')
    in_default = False
    for match in token.finditer(body):
        text = match.group(0)
        if text.startswith("case"):
            if in_default:
                raise ValueError("a case label follows the default.")
            pending.append(match.group(1))
        elif text.startswith("default"):
            if pending:
                raise ValueError(f"case labels share the default: {pending}")
            in_default = True
        elif in_default:
            default = match.group(2)
            in_default = False
        else:
            if not pending:
                raise ValueError(f"a return without a case label: {text}")
            cases.extend((label, match.group(2)) for label in pending)
            pending = []
    if pending:
        raise ValueError(f"case labels without a return: {pending}")
    if default is None:
        raise ValueError("the switch has no default return.")
    seen: set[str] = set()
    for label, _ in cases:
        if label in seen:
            raise ValueError(f"'{label}' is a case twice.")
        seen.add(label)
    return cases, default


def source_label(path: Path) -> str:
    """The converter's path from the metaboservice source folder down, or its name when it is elsewhere."""
    parts = path.resolve().parts
    for index in range(len(parts) - 1, -1, -1):
        if parts[index].casefold() == SOURCE_FOLDER.casefold():
            return "/".join((SOURCE_FOLDER, *parts[index + 1:]))
    return path.name


def table_lines(source: str, label: str, sha256: str, size: int) -> list[str]:
    cases, default = parse_superclass_switch(source)
    lines = [
        "# Generated by scripts/generate-lipid-category-table.py from metaboservice's own LipidomicsConverter.cs",
        "# (ConvertMsdialClassDefinitionToSuperClassVS2), the CommonStandard copy metaboservice.csproj references.",
        f"{SOURCE_LINE}{label} sha256 {sha256} ({size} bytes)",
        "# Not MsdialWorkbench's current switch: a class newer than this copy is 'Unassigned lipid', as metaboservice",
        "# filed it. Do not edit by hand.",
        "# case: an Ontology the switch names, and the lipid category it returns, in source order.",
        "# default: the category of every other Ontology.",
        "kind\tclass\tcategory",
    ]
    lines.extend(f"case\t{name}\t{category}" for name, category in cases)
    lines.append(f"default\t\t{default}")
    return lines


def read_converter(path: Path) -> tuple[Path, bytes]:
    """The converter file, given it or the metaboservice source folder that holds it."""
    target = path / CONVERTER_SOURCE if path.is_dir() else path
    if not target.is_file():
        raise ValueError(f"{target} is not a file.")
    return target, target.read_bytes()


def main() -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("source", type=Path,
                        help=f"the {SOURCE_FOLDER} folder, or its {CONVERTER_SOURCE.name}; read only")
    parser.add_argument("--check", action="store_true", help="compare with the resource; write nothing")
    arguments = parser.parse_args()
    try:
        target, data = read_converter(arguments.source)
        lines = table_lines(data.decode("utf-8-sig"), source_label(target), hashlib.sha256(data).hexdigest(), len(data))
    except (OSError, ValueError, UnicodeDecodeError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2
    if arguments.check:
        current = OUTPUT.read_text(encoding="ascii") if OUTPUT.exists() else ""
        # The source line is compared too: the same switch read from another file is another source.
        def kept(text_lines):
            return [line for line in text_lines if not line.startswith("#") or line.startswith(SOURCE_LINE)]

        same = kept(current.splitlines()) == kept(lines)
        print("unchanged" if same else "differs")
        return 0 if same else 1
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    cases = sum(1 for line in lines if line.startswith("case\t"))
    print(f"wrote {OUTPUT} ({cases} classes, {source_label(target)})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
